<h1>About</h1>

<p>
    This Point of Sale (POS) application was built with CodeIgniter 4 for IT0049 (Web System Technologies).
    It was developed step by step across the course's activities:
</p>

<ul class="about-list">
    <li><strong>TFA1</strong> &ndash; Pages and routing, with records kept in static PHP arrays.</li>
    <li><strong>TFA2</strong> &ndash; The arrays were replaced with a MySQL database read through CodeIgniter Models.</li>
    <li><strong>TFA3</strong> &ndash; Validated forms for creating and editing records, and avatar upload.</li>
    <li>
        <strong>Midterm</strong> &ndash; Product management with images, staff login with hashed passwords,
        and a sales workflow that records each transaction and decreases the product's stock.
    </li>
</ul>

<h2>Built with</h2>
<ul>
    <li>PHP 8.2+ and CodeIgniter 4</li>
    <li>MySQL</li>
    <li>HTML, CSS, and a little JavaScript</li>
</ul>
