<h1>About</h1>

<p>
    This Point of Sale (POS) application was built with CodeIgniter 4 for IT0049 (Web System Technologies).
</p>

<ul class="about-list">
    <li><strong>TFA1</strong> &ndash; Customer and user records were kept in static PHP arrays.</li>
    <li>
        <strong>TFA2</strong> &ndash; The arrays were replaced with a MySQL database. Each page reads its records
        through a CodeIgniter Model (<code>CustomerModel</code> and <code>UserModel</code>) using Query Builder.
    </li>
    <li>
        <strong>TFA3</strong> &ndash; Customers and users can now be created and edited through validated forms,
        and each user can upload a profile picture that is resized into a thumbnail.
    </li>
</ul>

<h2>Built with</h2>
<ul>
    <li>PHP 8.2+ and CodeIgniter 4</li>
    <li>MySQL</li>
    <li>HTML and CSS</li>
</ul>
